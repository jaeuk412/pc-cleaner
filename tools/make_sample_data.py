"""테스트용 샘플 폴더를 생성합니다.

    python tools/make_sample_data.py            # ./sample_data 생성
    python tools/make_sample_data.py --out D:/x # 다른 위치에 생성

생성 내용:
  - 업무 문서/사진/계측 데이터 (정상 파일)
  - 다른 폴더에 복사된 중복 파일 (다운로드 폴더에 같은 파일이 여러 번 저장된 상황 재현)
  - 수정 날짜가 60~200일 전인 임시 파일(.tmp/.log/.bak/__pycache__)
  - 최근에 만든 임시 파일 (기준 일수 미만이므로 정리 대상이 아니어야 함)

※ Git은 파일의 수정 날짜를 보존하지 않으므로 '오래된 파일'은 저장소에 그대로 올리지 않고
  이 스크립트로 매번 생성합니다. 같은 seed면 항상 같은 내용이 만들어집니다.
"""
from __future__ import annotations

import argparse
import os
import random
import shutil
import time
from pathlib import Path

DAY = 24 * 60 * 60
MARKER = ".pccleaner_sample"


def _write(path: Path, data: bytes, age_days: float = 0) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    if age_days:
        t = time.time() - age_days * DAY
        os.utime(path, (t, t))


def _copy(src: Path, dst: Path, age_days: float = 0) -> None:
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(src, dst)
    if age_days:
        t = time.time() - age_days * DAY
        os.utime(dst, (t, t))


def make_sample(out: Path, seed: int = 42) -> Path:
    rng = random.Random(seed)
    rnd = lambda n: rng.randbytes(n)  # noqa: E731

    # 안전장치: 이 스크립트가 만든 폴더(표식 파일 있음)이거나 빈 폴더일 때만 지우고 다시 만듭니다.
    # --out에 실수로 중요한 폴더를 지정해도 삭제되지 않게 합니다.
    if out.exists():
        if (out / MARKER).exists():
            shutil.rmtree(out)
        elif any(out.iterdir()):
            raise SystemExit(f"[중단] {out} 폴더가 비어 있지 않고 샘플 폴더 표식도 없습니다. 다른 경로를 지정하세요.")
    out.mkdir(parents=True, exist_ok=True)
    (out / MARKER).write_text("generated by tools/make_sample_data.py\n", encoding="utf-8")

    # 1) 정상 업무 파일
    _write(out / "work/report_2026_Q3.docx", rnd(180_000), age_days=90)
    _write(out / "work/meeting_notes.txt", "주간 회의록\n- 백업 정책 논의\n".encode("utf-8") * 200, age_days=40)
    _write(out / "work/budget.xlsx", rnd(95_000), age_days=70)
    csv = "time_s,voltage_v,current_a\n" + "".join(
        f"{i * 0.001:.3f},{3.3 + rng.uniform(-0.05, 0.05):.4f},{0.12 + rng.uniform(-0.01, 0.01):.4f}\n"
        for i in range(20_000)
    )
    _write(out / "work/measurements/psu_sweep_25C.csv", csv.encode(), age_days=30)
    _write(out / "photos/2026_trip/IMG_0001.jpg", rnd(1_200_000), age_days=150)
    _write(out / "photos/2026_trip/IMG_0002.jpg", rnd(950_000), age_days=150)
    _write(out / "videos/demo_recording.mp4", rnd(4_000_000), age_days=20)
    _write(out / "installers/tool_setup_v2.3.exe", rnd(3_000_000), age_days=120)

    # 2) 중복 파일 (원본보다 나중에 복사된 것 → 복사본이 정리 대상)
    _copy(out / "photos/2026_trip/IMG_0001.jpg", out / "downloads/IMG_0001.jpg", age_days=100)
    _copy(out / "photos/2026_trip/IMG_0001.jpg", out / "downloads/IMG_0001 (1).jpg", age_days=99)
    _copy(out / "installers/tool_setup_v2.3.exe", out / "downloads/tool_setup_v2.3.exe", age_days=110)
    _copy(out / "work/report_2026_Q3.docx", out / "desktop/report_2026_Q3_최종.docx", age_days=80)
    _copy(out / "videos/demo_recording.mp4", out / "desktop/backup_copy/demo_recording.mp4", age_days=10)

    # 크기는 같지만 내용이 다른 파일 (중복으로 잡히면 안 됨)
    _write(out / "work/measurements/raw_a.bin", rnd(200_000), age_days=30)
    _write(out / "work/measurements/raw_b.bin", rnd(200_000), age_days=30)

    # 3) 오래된 임시 파일
    _write(out / "work/~$report_2026_Q3.docx", rnd(162), age_days=89)
    _write(out / "downloads/chrome_download.tmp", rnd(800_000), age_days=200)
    _write(out / "logs/app_2026-05.log", b"INFO started\n" * 40_000, age_days=180)
    _write(out / "logs/app_2026-06.log", b"WARN retry\n" * 30_000, age_days=150)
    _write(out / "work/budget.xlsx.bak", rnd(95_000), age_days=65)
    _write(out / "projects/sim/__pycache__/solver.cpython-313.pyc", rnd(45_000), age_days=60)
    _write(out / "projects/sim/__pycache__/plot.cpython-313.pyc", rnd(22_000), age_days=60)
    _write(out / "projects/sim/solver.py", b"def solve():\n    return 42\n", age_days=60)

    # 4) 최근 임시 파일 (30일 기준이면 정리 대상 아님)
    _write(out / "logs/app_today.log", b"INFO running\n" * 5_000, age_days=1)
    _write(out / "downloads/in_progress.tmp", rnd(50_000), age_days=0)

    return out


def main() -> None:
    parser = argparse.ArgumentParser(description="PC Cleaner 샘플 데이터 생성")
    parser.add_argument("--out", default="sample_data", help="생성할 폴더 (기존 폴더는 삭제 후 재생성)")
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()
    out = make_sample(Path(args.out), args.seed)
    count = sum(1 for p in out.rglob("*") if p.is_file())
    size = sum(p.stat().st_size for p in out.rglob("*") if p.is_file())
    print(f"샘플 데이터 생성 완료: {out.resolve()}  (파일 {count}개, {size / 1024 / 1024:.1f} MB)")


if __name__ == "__main__":
    main()
